_HEX = "0123456789ABCDEF"
_CHECK_CHARS = "GHJKLMNPRSTVWXYZ"
_PREFIX = bytes((0x04, 0xC0, 0x5B))


def _check_char(address: bytes) -> str:
    """Return the check character of a long address."""
    crc = 2
    for byte in address:
        crc = _CRC_TABLE[byte ^ (crc << 4)]
    return _CHECK_CHARS[crc]


def barcode(address: bytes) -> str | None:
    """Return the barcode of an optimizer, like 4-9A57A2L.

    Returns None for addresses outside the Tigo range.
    """
    if len(address) != 8 or address[:3] != _PREFIX:
        return None
    nibbles = [address[3] & 0xF]
    for byte in address[4:]:
        nibbles.extend((byte >> 4, byte & 0xF))
    digits = "".join(_HEX[n] for n in nibbles).lstrip("0")
    return f"{_HEX[address[3] >> 4]}-{digits}{_check_char(address)}"
